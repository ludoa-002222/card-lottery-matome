  /**
   * 応募URLと形式（online/store）から表示するガイドを1件返す。
   * ホスト名は後方一致で判定する（seagull.membercard.jp → membercard.jp を拾うため）。
   */
  function resolveApplyGuide(applyUrl, method) {
    let host = "";
    try {
      host = new URL(applyUrl).hostname.replace(/^www\./, "");
    } catch (e) {
      host = "";
    }
    if (host) {
      const hit = GUIDES.find((g) =>
        g.hosts.some((h) => host === h || host.endsWith("." + h))
      );
      if (hit) return hit;
    }
    return FALLBACK[method] || FALLBACK.online;
  }

  window.ORIPA_APPLY_GUIDES = { resolve: resolveApplyGuide, guides: GUIDES };
